export function getProjectWorkspaceFixture(projectId: string): ProjectWorkspaceFixture | null {
  return MOCK_PROJECT_WORKSPACES[projectId] ?? null
}

export function getProjectWorkspaceFixturesByCompany(companyId: string): ProjectWorkspaceFixture[] {
  return Object.values(MOCK_PROJECT_WORKSPACES).filter(fixture => fixture.project.companyId === companyId)
}

export function getVisibleProjectPhases(
  fixture: ProjectWorkspaceFixture,
  audience: ProjectAudience,
): ProjectPhaseSummary[] {
  return fixture.phases.filter(phase => audience === 'internal' || phase.isClientVisible)
}

export function getVisibleProjectTasks(
  fixture: ProjectWorkspaceFixture,
  viewer: ProjectWorkspaceViewerContext,
) {
  if (viewer.role === 'SYSTEM_ADMIN' || viewer.role === 'PROJECT_LEAD' || viewer.role === 'DELIVERY_SPECIALIST') {
    return fixture.internal.tasks
  }

  if (viewer.role === 'COLLABORATOR') {
    return fixture.internal.tasks.filter(
      (task) => task.visibleToClient && Boolean(viewer.currentUserId) && task.assigneeUserId === viewer.currentUserId,
    )
  }

  return fixture.internal.tasks.filter((task) => task.visibleToClient)
}

export function getProjectActivityForAudience(
  fixture: ProjectWorkspaceFixture,
  audience: ProjectAudience,
): ProjectActivityEvent[] {
  const visibleEvents = audience === 'internal'
    ? [...fixture.activity.shared, ...fixture.activity.internal]
    : fixture.activity.shared

  return visibleEvents.sort((left, right) => right.happenedAt.getTime() - left.happenedAt.getTime())
}
